/* Применяет словарь текущего языка ко всем элементам с data-i18n / data-i18n-ph */
window.applyI18n = function (lang) {
  var dict = window.I18N[lang] || window.I18N.ru;
  var fallback = window.I18N.ru;

  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    var val = dict[key] != null ? dict[key] : fallback[key];
    if (val != null) el.innerHTML = val;
  });

  document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
    var key = el.getAttribute('data-i18n-ph');
    var val = dict[key] != null ? dict[key] : fallback[key];
    if (val != null) el.setAttribute('placeholder', val);
  });

  document.documentElement.setAttribute('lang', lang === 'kk' ? 'kk' : lang === 'en' ? 'en' : 'ru');

  if (typeof window.applyPrices === 'function') window.applyPrices();
  window.dispatchEvent(new CustomEvent('i18n:applied', { detail: { lang: lang } }));
};
